package tsumugi.diary;

import java.util.List;
import java.util.concurrent.ThreadLocalRandom;

/**
 * 日記の要約生成がすぐに処理できず、diary_queueで順番待ちになった際に
 * その場で返す案内メッセージのテンプレート集。
 *
 * 日記部屋はアクセスが集中しやすいため、待たせていること自体を隠さず、
 * かつ同じ文言の繰り返しにならないようランダムに選ぶ。
 */
public final class DiaryWaitingMessages {

    private static final List<String> TEMPLATES = List.of(
            "ごめんなさい、いま日記のご利用が集中していて…！記録はちゃんと受け取ったので、順番が来たら総評をお届けしますね😊",
            "わ、今たくさんの人が日記を書いているみたいです…！少しだけ待っていてくださいね📔",
            "ただいま日記の順番待ちが発生しています。ごめんなさい、落ち着いたら必ずお返事しますね。",
            "今日はみんな日記を頑張っているみたいです✨ 少し混み合っているので、少々お待ちください。",
            "受け取りました！ただ今立て込んでいるので、順番が来たら総評をお送りしますね。少しだけ待っていてください🙏",
            "ごめんなさい、只今処理待ちが多くなっています。あなたの記録は大切に保管していますので、ご安心くださいね。",
            "只今アクセスが集中しております。順番にお返事していますので、もう少しだけお時間をくださいね😊",
            "日記、確かに受け取りました！今ちょっと混んでいるので、落ち着き次第すぐお届けします。",
            "ただいま多くの方から日記が届いています。あなたの分もちゃんと順番に処理しますので、少々お待ちください。",
            "ごめんなさい、今は少し順番待ちが発生しています。処理が終わり次第、この部屋に総評をお送りしますね📔"
    );

    private DiaryWaitingMessages() {}

    public static String random() {
        return TEMPLATES.get(ThreadLocalRandom.current().nextInt(TEMPLATES.size()));
    }
}